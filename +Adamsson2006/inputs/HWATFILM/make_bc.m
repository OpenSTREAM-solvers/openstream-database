diam=14E-3;                                                                % [m]
perim=pi*diam;                                                             % [m]
area=pi*diam^2/4;                                                          % [m2]
elev=[0 cumsum(wmesh)];                                                   % [m]
rpowdist=[0 cumsum(wpower)]./sum(wpower);                                  % [-] Relative power distribution

for i=1:length(testid)
    
    % Power calculation
    p=pressure(i)*1E6;                                                     % [Pa]
    hf=py.CoolProp.CoolProp.PropsSI('H','P',p,'Q',0,'Water');              % [J/kg]
    hg=py.CoolProp.CoolProp.PropsSI('H','P',p,'Q',1,'Water');              % [J/kg]
    tin=py.CoolProp.CoolProp.PropsSI('T','P',p,'Q',0,'Water')-subcooling(i); % [F]
    hin=py.CoolProp.CoolProp.PropsSI('H','P',p,'T',tin,'Water');           % [J/kg]
    hout=quality(i)*(hg-hf)+hf;                                            % [J/kg]
    M=massflux(i)*area;                                                    % [kg/s]
    power=(hout-hin)*M;                                                    % [W]
    
    h=hin+rpowdist.*power./M;                                              % [J/kg]
    x=(h-hf)./(hg-hf);                                                     % [-]
    steamflow=max(0,x.*M);                                                 % [kg/s]
    
    % Boundary conditions
    bc(i).TESTID=[id '_' testid{i}];
    bc(i).TIME=0;
    bc(i).PRESSURE=p;                                                      % [Pa]
    bc(i).MFLOW=M;                                                         % [kg/s]
    bc(i).POWER=power;                                                     % [W]
    bc(i).HIN=hin;                                                         % [J/kg]
    bc(i).WMESH=wmesh;                                                     % [m]
    bc(i).WPOWER=wpower;                                                   % [-]
    bc(i).TIN=tin;                                                         % [F]
    bc(i).HOUT=hout;                                                       % [J/kg]
    bc(i).XOUT=quality(i);                                                 % [-]
    bc(i).ELEV=elevation{i};                                               % [m]
    bc(i).STEAMFLOW=interp1(elev,steamflow,bc(i).ELEV,'linear');           % [kg/s]
    bc(i).FILMFLOW=filmflow{i}./60;                                        % [kg/s]
    bc(i).DROPFLOW=M-bc(i).FILMFLOW-bc(i).STEAMFLOW;                       % [kg/s]
    
    writeInputFile([id '_' testid{i} '.inp'],bc(i))
    
    figure('Name',['Case ' id ' - ' testid{i} ' [kg/s/m^2]'],'NumberTitle','off');
    subplot(1,2,1);hold all; grid on;
    z=[0:0.01:sum(wmesh)];
    plot(bc(i).ELEV,bc(i).FILMFLOW,'ko','MarkerSize',8,'LineWidth',2)
    plot(bc(i).ELEV,bc(i).DROPFLOW,'ks','MarkerSize',8,'LineWidth',2)
    plot(bc(i).ELEV,bc(i).STEAMFLOW,'kx','MarkerSize',8,'LineWidth',2)
    plot(z,interp1(elev,steamflow,z,'linear'),'b-','LineWidth',2)
    %axis([0 4 0 0.1])
    xlim([0 4])
    xlabel('Elevation [m]'); ylabel('Flow rates [kg/s]');
    legend({'Film','Drop','Vapor'},'Location','NorthWest');
    set(gca,'FontSize',14);
    
    subplot(1,2,2);hold all; grid on;
    plot(bc(i).STEAMFLOW./M,bc(i).FILMFLOW./M,'ko','MarkerSize',8,'LineWidth',2)
    xlim([0.2 1]); ylim([0 0.25])
    xlabel('Steam quality [-]'); ylabel('Flow fraction [-]');
    set(gca,'FontSize',14);
